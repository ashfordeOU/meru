const SEED: [u8; 32] = *b"meru-service-test-key-32-bytes!!";
const T: i64 = 1_795_132_800; // 2026-11-20T00:00:00Z

fn pk(seed: &[u8; 32]) -> String {
    hex::encode(seed.public_key().unwrap())
}

fn req(id: &str, reason: Reason, revoked: Option<&str>) -> RevokeRequest {
    RevokeRequest {
        id: id.into(),
        revoked: revoked.map(String::from),
        reason,
        note: Some("private: firmware 4.2 regression found in bench re-run".into()),
    }
}

fn tmp(tag: &str) -> PathBuf {
    let p = std::env::temp_dir().join(format!("meru-crl-{tag}-{}.jsonl", std::process::id()));
    let _ = std::fs::remove_file(&p);
    p
}

/// The open format's test vector (generated by the open side from its documented rule): the
/// public test seed SHA-256("register crl test vector"), the document, and its signature. Our
/// issuing reproduces it byte for byte, and our reader accepts it.
#[test]
fn the_open_format_vector_is_reproduced() {
    let seed: [u8; 32] = Sha256::digest(b"register crl test vector").into();
    assert_eq!(
        pk(&seed),
        "a028f6212dcbd196a38fe8e13927a9d997f4d72ab00341276b9437d8f2273a8d"
    );
    let revoked = vec![
        Revocation {
            id: "rx-007".into(),
            revoked: "2026-11-19".into(),
            reason: Reason::ScoreWithdrawn.text().into(),
        },
        Revocation {
            id: "ant-12.v2".into(),
            revoked: "2026-11-20".into(),
            reason: Reason::MethodSuperseded.text().into(),
        },
    ];
    let doc = issue("Example issuer (test vector)", &revoked, &seed, T + 3600).unwrap();
    let mut unsigned = doc.clone();
    unsigned.signature = String::new();
    assert_eq!(
        hex::encode(Sha256::digest(signing_bytes(&unsigned))),
        "2852716a734dead2a0086f51242861c964d63f99f7ff93165277cbb8caaabb4b"
    );
    let expected = include_str!("../docs/crl-vector.json").trim_end();
    assert_eq!(serde_json::to_string(&doc).unwrap(), expected);
    // The vector as given parses (unknown fields refused) and verifies.
    let parsed: CrlDoc = serde_json::from_str(expected).unwrap();
    let v = check(&parsed, &pk(&seed), "2026-11-20").unwrap();
    assert!(!v.stale);
    assert_eq!(v.revoked_ids, ["rx-007", "ant-12.v2"]);
    // A revocation dated later does not apply yet; past next_update the list is stale but its
    // revocations still apply.
    assert_eq!(
        check(&parsed, &pk(&seed), "2026-11-19")
            .unwrap()
            .revoked_ids,
        ["rx-007"]
    );
    let late = check(&parsed, &pk(&seed), "2026-12-01").unwrap();
    assert!(late.stale && late.revoked_ids.len() == 2);
    // Another issuer key, a changed field, an extra field: refused.
    assert!(check(&parsed, &pk(&SEED), "2026-11-20").is_err());
    let mut t = parsed.clone();
    t.revoked[0].reason = "holder request".into();
    assert!(check(&t, &pk(&seed), "2026-11-20").is_err());
    let extra = expected.replacen("{\"schema\"", "{\"seq\":2,\"schema\"", 1);
    assert!(serde_json::from_str::<CrlDoc>(&extra).is_err());
}

#[test]
fn revocations_persist_and_the_list_is_issued_daily() {
    let p = tmp("persist");
    let mut s = CrlStore::open(&p).unwrap();
    let r = s
        .revoke(&req("rx-100", Reason::ProductChanged, None), "kt_admin", T)
        .unwrap();
    assert_eq!(r.revoked, "2026-11-20");
    assert_eq!(r.reason, "product changed");
    s.revoke(
        &req("ant-3", Reason::EvidenceError, Some("2026-12-01")),
        "kt_admin",
        T,
    )
    .unwrap();
    // An id already revoked is refused; bad ids, dates and notes are refused.
    assert!(s
        .revoke(&req("rx-100", Reason::HolderRequest, None), "kt", T)
        .unwrap_err()
        .starts_with("already revoked"));
    assert!(s
        .revoke(&req("rx 1", Reason::HolderRequest, None), "kt", T)
        .is_err());
    assert!(s
        .revoke(&req("a/b", Reason::HolderRequest, None), "kt", T)
        .is_err());
    assert!(s
        .revoke(
            &req("rx-2", Reason::HolderRequest, Some("2026-02-30")),
            "kt",
            T
        )
        .is_err());
    let mut long = req("rx-3", Reason::HolderRequest, None);
    long.note = Some("x".repeat(501));
    assert!(s.revoke(&long, "kt", T).is_err());

    let d = s.current("", &SEED, T + 60).unwrap();
    assert_eq!(d.schema, SCHEMA);
    assert_eq!(d.issuer, DEFAULT_ISSUER);
    assert_eq!(
        (d.issued.as_str(), d.next_update.as_str()),
        ("2026-11-20", "2026-11-27")
    );
    assert_eq!(d.revoked.len(), 2);
    assert_eq!(d.signer, pk(&SEED));
    let v = check(&d, &pk(&SEED), "2026-11-20").unwrap();
    assert_eq!(v.revoked_ids, ["rx-100"]);
    // The same day: the same document; the next day: re-issued.
    assert_eq!(s.current("", &SEED, T + 7200).unwrap(), d);
    assert_eq!(
        s.current("", &SEED, T + 86_400).unwrap().issued,
        "2026-11-21"
    );
    // The private note and the revoking licence are not in the document.
    let text = serde_json::to_string(&d).unwrap();
    assert!(!text.contains("bench re-run") && !text.contains("kt_admin"));
    // Field order is the format's.
    assert!(text.starts_with(r#"{"schema":"kshana.register-crl/1","issuer":"#));
    assert!(text.contains(
        r#""revoked":[{"id":"rx-100","revoked":"2026-11-20","reason":"product changed"}"#
    ));
    // Restart: read back.
    let mut s2 = CrlStore::open(&p).unwrap();
    assert_eq!(s2.entries(), s.entries());
    assert_eq!(s2.current("", &SEED, T + 60).unwrap(), d);
    // A non-ASCII issuer is refused (the open reader's bytes would differ).
    assert!(s2.current("Émetteur", &SEED, T).is_err());
    let _ = std::fs::remove_file(&p);
}

#[test]
fn log_lines_from_the_earlier_format_are_read() {
    let p = tmp("legacy");
    std::fs::write(
        &p,
        r#"{"revoked":{"product_id":"RX-1","scored_under":{"method":"m","version":"1"},"verdict_sha256":null,"reason":"holder_request","revoked_utc":"2026-11-01T10:00:00Z"},"by_token_id":"kt","note":null}
"#,
    )
    .unwrap();
    let s = CrlStore::open(&p).unwrap();
    assert_eq!(
        s.entries(),
        [Revocation {
            id: "RX-1".into(),
            revoked: "2026-11-01".into(),
            reason: "holder request".into()
        }]
    );
    std::fs::write(&p, "{\"nonsense\":1}\n").unwrap();
    assert!(CrlStore::open(&p).is_err());
    let _ = std::fs::remove_file(&p);
}

#[test]
fn the_record_hash_is_over_the_compact_revocation() {
    let r = Revocation {
        id: "rx-007".into(),
        revoked: "2026-11-19".into(),
        reason: "score withdrawn".into(),
    };
    assert_eq!(
        record_sha256(&r),
        hex::encode(Sha256::digest(
            r#"{"id":"rx-007","revoked":"2026-11-19","reason":"score withdrawn"}"#
        ))
    );
}
